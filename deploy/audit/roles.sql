CREATE ROLE saku_owner WITH LOGIN PASSWORD 'change-me-owner' CREATEDB;

CREATE ROLE saku_app WITH LOGIN PASSWORD 'change-me-app';

GRANT USAGE ON SCHEMA public TO saku_app;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO saku_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO saku_app;
ALTER DEFAULT PRIVILEGES FOR ROLE saku_owner IN SCHEMA public
	GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO saku_app;

REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON audit_logs FROM saku_app;
GRANT SELECT ON audit_logs TO saku_app;